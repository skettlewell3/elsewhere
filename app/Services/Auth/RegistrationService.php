<?php

namespace App\Services\Auth;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use RuntimeException;
use Throwable;

class RegistrationService
{
    public function __construct(
        private readonly SignupCodeService $signupCodes,
        private readonly RegistrationAttemptService $attempts,
        private readonly SupabaseAuthService $supabaseAuth
    ) {}

    public function register(
        string $firstName,
        string $lastName,
        string $email,
        string $password,
        string $signupCode
    ): array {
        $firstName = trim($firstName);
        $lastName = trim($lastName);
        $email = strtolower(trim($email));
        $signupCode = trim($signupCode);

        $token = $this->signupCodes->reserve(
            $signupCode,
            $email
        );

        if ($token === null) {
            return $this->result(
                'rejected',
                'invalid_signup_code'
            );
        }

        try {
            $attemptId = $this->attempts->create(
                $token,
                $email
            );
        } catch (Throwable $exception) {
            $this->signupCodes->release($token);

            throw $exception;
        }

        if ($attemptId === null) {
            $this->signupCodes->release($token);

            return $this->result(
                'rejected',
                'attempt_creation_failed'
            );
        }

        if (! $this->attempts->beginAuthCreation($attemptId)) {
            $this->markUncertain(
                $attemptId,
                'auth_start_failed'
            );

            return $this->result(
                'needs_reconciliation',
                'auth_start_failed',
                $attemptId
            );
        }

        /*
         * Supabase Auth creation is an external operation.
         * Never automatically retry an uncertain signup.
         */
        try {
            $signup = $this->supabaseAuth->signUp(
                $email,
                $password,
                $firstName,
                $lastName,
                $token
            );
        } catch (Throwable $exception) {
            report($exception);

            $this->markUncertain(
                $attemptId,
                'signup_request_exception'
            );

            return $this->result(
                'needs_reconciliation',
                'signup_request_exception',
                $attemptId
            );
        }

        if (($signup['outcome'] ?? null) !== 'response_received') {
            $errorCode = $signup['error_code']
                ?? 'signup_unconfirmed';

            $this->markUncertain(
                $attemptId,
                $errorCode
            );

            return $this->result(
                'needs_reconciliation',
                $errorCode,
                $attemptId
            );
        }

        $authId = $signup['auth_id'] ?? null;

        if (! is_string($authId) || ! Str::isUuid($authId)) {
            $this->markUncertain(
                $attemptId,
                'invalid_auth_identity'
            );

            return $this->result(
                'needs_reconciliation',
                'invalid_auth_identity',
                $attemptId
            );
        }

        /*
         * A successful signup response alone is not
         * sufficient proof of a new Auth identity.
         *
         * The Before User Created hook must have
         * claimed exactly this UUID for this attempt.
         */
        try {
            $attempt = $this->attempts->find($attemptId);

            $claimMatches = $attempt !== null
                && $attempt->status === 'creating_auth'
                && strtolower((string) $attempt->auth_id)
                    === strtolower($authId);

            if (! $claimMatches) {
                $this->markUncertain(
                    $attemptId,
                    'auth_claim_unverified'
                );

                return $this->result(
                    'needs_reconciliation',
                    'auth_claim_unverified',
                    $attemptId
                );
            }

            /*
             * Check the actual Auth user and the
             * account generated by the existing
             * on_auth_user_created database trigger.
             */
            $account = DB::table('auth.users as u')
                ->join(
                    'public.accounts_users as au',
                    'au.auth_id',
                    '=',
                    'u.id'
                )
                ->join(
                    'public.accounts as a',
                    'a.account_id',
                    '=',
                    'au.account_id'
                )
                ->where('u.id', $authId)
                ->whereRaw('lower(u.email) = ?', [$email])
                ->select(
                    'au.account_id',
                    'au.auth_id'
                )
                ->first();
        } catch (Throwable $exception) {
            report($exception);

            $this->markUncertain(
                $attemptId,
                'account_verification_unavailable'
            );

            return $this->result(
                'needs_reconciliation',
                'account_verification_unavailable',
                $attemptId
            );
        }

        if ($account === null) {
            $this->markUncertain(
                $attemptId,
                'account_not_provisioned'
            );

            return $this->result(
                'needs_reconciliation',
                'account_not_provisioned',
                $attemptId
            );
        }

        /*
         * Auth creation has been independently verified.
         */
        try {
            $confirmed = $this->attempts->confirmAuthCreated(
                $attemptId,
                $authId,
                $email
            );

            if (! $confirmed) {
                $this->markUncertain(
                    $attemptId,
                    'auth_confirmation_failed'
                );

                return $this->result(
                    'needs_reconciliation',
                    'auth_confirmation_failed',
                    $attemptId
                );
            }

            if (! $this->attempts->beginProvisioning($attemptId)) {
                $this->markUncertain(
                    $attemptId,
                    'provisioning_start_failed'
                );

                return $this->result(
                    'needs_reconciliation',
                    'provisioning_start_failed',
                    $attemptId
                );
            }

            /*
             * Account creation itself was already
             * performed by the Supabase database trigger.
             *
             * Only populate the identity fields here,
             * redeem the invitation, and finalise the
             * registration attempt.
             *
             * These changes share one Laravel database
             * transaction so they succeed or roll back
             * together.
             */
            DB::transaction(function () use (
                $attemptId,
                $token,
                $authId,
                $email,
                $firstName,
                $lastName,
                $account
            ) {
                $updated = DB::table('accounts_users')
                    ->where('auth_id', $authId)
                    ->where('account_id', $account->account_id)
                    ->update([
                        'first_name' => $firstName,
                        'last_name' => $lastName,
                        'updated_at' => now(),
                    ]);

                if ($updated !== 1) {
                    throw new RuntimeException(
                        'Unable to update account identity.'
                    );
                }

                if (! $this->signupCodes->redeem(
                    $token,
                    $authId,
                    $email
                )) {
                    throw new RuntimeException(
                        'Unable to redeem signup invitation.'
                    );
                }

                if (! $this->attempts->complete($attemptId)) {
                    throw new RuntimeException(
                        'Unable to complete registration.'
                    );
                }
            }, 3);
        } catch (Throwable $exception) {
            report($exception);

            $this->markUncertain(
                $attemptId,
                'registration_finalisation_failed'
            );

            return $this->result(
                'needs_reconciliation',
                'registration_finalisation_failed',
                $attemptId
            );
        }

        return $this->result(
            'completed',
            null,
            $attemptId
        );
    }

    private function result(
        string $status,
        ?string $errorCode,
        ?int $attemptId = null
    ): array {
        return [
            'status' => $status,
            'error_code' => $errorCode,
            'attempt_id' => $attemptId,
        ];
    }

    private function markUncertain(
        int $attemptId,
        string $errorCode
    ): void {
        $this->attempts->needsReconciliation(
            $attemptId,
            substr($errorCode, 0, 100)
        );
    }
}
